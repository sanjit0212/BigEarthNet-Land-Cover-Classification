import os
from docx import Document
from docx.shared import Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH

def add_code_block(doc, code_text):
    # Add a paragraph with a specific style for code
    p = doc.add_paragraph()
    run = p.add_run(code_text)
    run.font.name = 'Courier New'
    run.font.size = Pt(9)
    p.paragraph_format.left_indent = Pt(20)

doc = Document()

doc.add_heading('Big Data Project: Complete Source Code Documentation', 0)
doc.add_paragraph('This document contains the complete source code utilized in the BigEarthNet Land Cover Classification project, along with technical explanations for each module.')
doc.add_page_break()

