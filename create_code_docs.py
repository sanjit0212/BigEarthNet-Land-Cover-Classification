base_dir = "C:/Users/sanji/Desktop/bda_project"

for file_info in files_to_document:
    doc.add_heading(file_info['title'], level=1)
    doc.add_paragraph(file_info['explanation'])
    
    file_path = os.path.join(base_dir, file_info['path'])
    
    if os.path.exists(file_path):
        doc.add_heading(f"File: {file_info['path']}", level=2)
        with open(file_path, 'r', encoding='utf-8') as f:
            code_content = f.read()
        
        # Docx has limits on single paragraph sizes, so we split by lines if it's too long
        add_code_block(doc, code_content)
    else:
        doc.add_paragraph(f"[Code file not found at {file_path}]")
        
    doc.add_page_break()

output_path = os.path.join(base_dir, "Code_Documentation.docx")
doc.save(output_path)
print(f"Successfully generated {output_path}")
